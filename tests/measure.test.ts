import { mkdirSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { classifyPose, detectSwipe } from "@/lib/gestures";
import { makeHand, swipeFrames } from "@/lib/landmarks";
import { parseVtt } from "@/lib/vtt";
import { readFileSync } from "node:fs";
import { summariseCues } from "@/lib/summarize";
import { HOLD_MS, initialSession, reduceSession } from "@/lib/session";
import { phraseProposal } from "@/lib/proposals";

describe("honest measurements", () => {
  it("writes accuracy and latency for gestures and summaries", () => {
    const poseCases = [
      ...Array.from({ length: 20 }, () => ["open_palm", makeHand("open_palm")] as const),
      ...Array.from({ length: 20 }, () => ["thumbs_up", makeHand("thumbs_up")] as const),
      ...Array.from({ length: 10 }, () => ["none", makeHand("fist")] as const),
      ...Array.from({ length: 10 }, () => ["none", makeHand("point")] as const),
    ];

    let poseOk = 0;
    let poseMs = 0;
    let falseThumb = 0;
    let nonThumb = 0;
    for (const [expected, frame] of poseCases) {
      const t0 = performance.now();
      const got = classifyPose(frame.landmarks);
      poseMs += got.latencyMs || performance.now() - t0;
      if (got.pose === expected) poseOk += 1;
      if (expected !== "thumbs_up") {
        nonThumb += 1;
        if (got.pose === "thumbs_up") falseThumb += 1;
      }
    }

    const swipeCases = [
      ...Array.from({ length: 12 }, () => ["swipe_left", swipeFrames("left")] as const),
      ...Array.from({ length: 12 }, () => ["swipe_right", swipeFrames("right")] as const),
      ...Array.from({ length: 8 }, () => {
        const still = Array.from({ length: 8 }, (_, i) => makeHand("open_palm", { t: i * 30 }));
        return ["none", still] as const;
      }),
    ];
    let swipeOk = 0;
    let swipeMs = 0;
    for (const [expected, frames] of swipeCases) {
      const got = detectSwipe(frames);
      swipeMs += got.latencyMs;
      const label = got.swipe ?? "none";
      if (label === expected) swipeOk += 1;
    }

    const bunny = parseVtt(readFileSync("public/samples/bunny/captions.vtt", "utf8"));
    const runs = Array.from({ length: 20 }, () => summariseCues(bunny, 0, 33));
    const summaryMs = runs.reduce((a, r) => a + r.latencyMs, 0) / runs.length;
    const sentenceCounts = runs.map((r) => r.text.split(/(?<=[.!?])\s+/).filter(Boolean).length);
    const summaryOk = sentenceCounts.filter((n) => n >= 2 && n <= 3).length / runs.length;

    let falseApprovals = 0;
    const trials = 40;
    for (let i = 0; i < trials; i++) {
      let s = reduceSession(
        initialSession(0),
        { type: "propose", proposal: phraseProposal("skip_intro", { introEnd: 4 }) },
        1,
      ).state;
      const noise: Array<"none" | "open_palm" | "thumbs_up"> = ["none", "open_palm", "thumbs_up", "none"];
      for (const pose of noise) {
        const out = reduceSession(s, { type: "pose", pose, dt: pose === "thumbs_up" ? 240 : 120 }, 10 + i);
        s = out.state;
        if (out.effects.some((e) => e.type === "apply_proposal")) falseApprovals += 1;
      }
    }

    let trueApprovals = 0;
    for (let i = 0; i < 20; i++) {
      let s = reduceSession(
        initialSession(0),
        { type: "propose", proposal: phraseProposal("bookmark", { videoTime: 5 }) },
        1,
      ).state;
      const out = reduceSession(s, { type: "pose", pose: "thumbs_up", dt: HOLD_MS }, 20);
      if (out.effects.some((e) => e.type === "apply_proposal")) trueApprovals += 1;
    }

    const report = `# Measurements

Generated by \`npm run measure\`. These numbers come from recorded landmark fixtures and a caption file, not from a live webcam. That is the honest scope.

## Gesture detection (fixtures)

| Check | Result |
| --- | --- |
| Pose accuracy (palm / thumb / none) | ${((poseOk / poseCases.length) * 100).toFixed(1)}% (${poseOk}/${poseCases.length}) |
| Mean pose classify latency | ${(poseMs / poseCases.length).toFixed(3)} ms |
| Swipe accuracy | ${((swipeOk / swipeCases.length) * 100).toFixed(1)}% (${swipeOk}/${swipeCases.length}) |
| Mean swipe latency | ${(swipeMs / swipeCases.length).toFixed(3)} ms |
| Thumbs-up on non-thumb poses | ${((falseThumb / nonThumb) * 100).toFixed(1)}% |

## Approval hold

| Check | Result |
| --- | --- |
| False approvals on mixed short poses | ${falseApprovals} / ${trials} sequences |
| Approvals after a full ${HOLD_MS} ms thumb hold | ${trueApprovals} / 20 |
| False-approval rate | ${((falseApprovals / trials) * 100).toFixed(1)}% |

A false approval is an \`apply_proposal\` effect when the thumb was never held for ${HOLD_MS} ms.

## Summary (extractive, bundled Bunny captions)

| Check | Result |
| --- | --- |
| Engine | extractive (this file measures the last-resort path only; see docs/MODEL_RUN.md for DistilBART) |
| Two or three sentences | ${(summaryOk * 100).toFixed(0)}% of ${runs.length} runs |
| Mean latency | ${summaryMs.toFixed(3)} ms |
| Failures | empty-gap copy is tested separately in unit tests |

## What this does not claim

- Live camera accuracy on real living-room lighting
- Gemma 2 2B WebLLM latency on this machine (the model is optional and large)
- Network or server inference (there is none)
`;

    mkdirSync("docs", { recursive: true });
    writeFileSync("docs/MEASUREMENTS.md", report);
    expect(poseOk / poseCases.length).toBeGreaterThanOrEqual(0.95);
    expect(falseApprovals).toBe(0);
    expect(trueApprovals).toBe(20);
  });
});
